"""Errors, paths and small helpers shared by every module."""

import os
import re
import shutil
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

CORE = Path(__file__).resolve().parents[2]
MARKER = "<!-- factory -->"
GENERATED = "Generated by `mfactory sync` from factory.toml. Do not edit"
LEGACY_GENERATED = "Generated by `factory sync` from factory.toml. Do not edit"
SOURCE_REPO = os.environ.get("FACTORY_SOURCE_REPO", "danielsmag/modular-factory")
SHARE_NAME: str = "modular-factory"
"""Directory under ``share/`` that holds the PyPI install's factory tree."""


class FactoryError(Exception):
    """Any failure the CLI reports without a traceback."""


class Refused(FactoryError):
    """An illegal move, or a precondition that doesn't hold."""


class ConfigError(FactoryError):
    """One or more problems in factory.toml, each naming its key."""

    def __init__(self, problems):
        self.problems = [problems] if isinstance(problems, str) else list(problems)
        super().__init__("\n".join(self.problems))


def version():
    return (CORE / "VERSION").read_text().strip()


def user_dir() -> Path:
    """This user's factory directory. `FACTORY_HOME` overrides `~/.mfactory`."""
    chosen: str | None = os.environ.get("FACTORY_HOME")
    if chosen:
        return Path(chosen).expanduser()
    return Path.home() / ".mfactory"


def is_generated(text: str) -> bool:
    """True when sync wrote this file, including files written before the mfactory rename."""
    return GENERATED in text or LEGACY_GENERATED in text


def adapters_dir():
    """`adapters/` sits next to `core/` in the source repo and inside `.factory/` once installed."""
    inside = CORE / "adapters"
    return inside if inside.is_dir() else CORE.parent / "adapters"


def web_dir() -> Path:
    """`web/` sits next to `core/` in the source repo and the global install. A project has no copy."""
    return CORE.parent / "web"


def running_distribution() -> Path | None:
    """``share/modular-factory`` when this process is the PyPI install. None from a checkout or ``.factory/``."""
    root: Path = CORE.parent
    binary: Path = root / "core" / "bin" / "mfactory"
    if root.name == SHARE_NAME and root.parent.name == "share" and binary.is_file():
        return root
    return None


def _prefix_binary(prefix: Path) -> Path | None:
    """``core/bin/mfactory`` inside a tool env's ``share/modular-factory``, when that file exists."""
    binary: Path = prefix / "share" / SHARE_NAME / "core" / "bin" / "mfactory"
    return binary if binary.is_file() else None


def _prefix_from_shebang(script: Path) -> Path | None:
    """The virtualenv root named by a console script's shebang. None when the file is not one."""
    try:
        lines: list[str] = script.read_text(errors="replace").splitlines()
    except OSError:
        return None
    if not lines or not lines[0].startswith("#!"):
        return None
    python: Path = Path(lines[0][2:].strip().split()[0])
    if not python.name.startswith("python"):
        return None
    resolved: Path = python.expanduser()
    if not resolved.is_file():
        return None
    return resolved.resolve().parent.parent


def tool_binary() -> Path | None:
    """The PyPI install's ``core/bin/mfactory``.

    Looks at this interpreter, then at ``mfactory`` on ``PATH``, then at the usual uv and pipx
    directories. ``FACTORY_SKIP_TOOL_SEARCH`` skips the search so tests do not see a developer's
    own install.
    """
    if os.environ.get("FACTORY_SKIP_TOOL_SEARCH") == "1":
        return None
    from_prefix: Path | None = _prefix_binary(Path(sys.prefix))
    if from_prefix is not None:
        return from_prefix
    found: str | None = shutil.which("mfactory")
    if found:
        script: Path = Path(found)
        prefix: Path | None = _prefix_from_shebang(script)
        if prefix is not None:
            binary: Path | None = _prefix_binary(prefix)
            if binary is not None:
                return binary
        if script.parent.name == "bin" and script.parent.parent.name == "core":
            root: Path = script.parent.parent.parent
            if (root / "web" / "dashboard.html").is_file():
                return script
    candidates: list[Path] = []
    tool_dir: str | None = os.environ.get("UV_TOOL_DIR")
    if tool_dir:
        candidates.append(Path(tool_dir).expanduser() / SHARE_NAME)
    else:
        candidates.append(Path.home() / ".local" / "share" / "uv" / "tools" / SHARE_NAME)
    pipx_home: str | None = os.environ.get("PIPX_HOME")
    if pipx_home:
        candidates.append(Path(pipx_home).expanduser() / "venvs" / SHARE_NAME)
    else:
        candidates.append(Path.home() / ".local" / "pipx" / "venvs" / SHARE_NAME)
    for prefix in candidates:
        installed: Path | None = _prefix_binary(prefix)
        if installed is not None:
            return installed
    return None


def global_binary() -> Path | None:
    """The global ``mfactory`` that has the dashboard page. None when nothing global is installed.

    A PyPI install wins over a copied ``~/.mfactory`` tree, so a machine that has both serves
    the package.
    """
    running: Path | None = running_distribution()
    if running is not None:
        return running / "core" / "bin" / "mfactory"
    found: Path | None = tool_binary()
    if found is not None:
        return found
    binary: Path = user_dir() / "core" / "bin" / "mfactory"
    if (user_dir() / ".global").is_file() and binary.is_file():
        return binary
    return None


def has_dashboard_page() -> bool:
    """True when `web/` is next to this copy: the global install or the source repo."""
    return (web_dir() / "dashboard.html").is_file()


def dashboard_page() -> bytes:
    """The dashboard as one document.

    `dashboard.css`, `markdown.js`, `dag.js` and `dashboard.js` are inlined. The browser is
    not given a separate file to load: the page's policy allows only inline style
    and script.
    """
    root: Path = web_dir()
    inlined: tuple[str, ...] = ("dashboard.css", "markdown.js", "dag.js", "dashboard.js")
    names: tuple[str, ...] = ("dashboard.html", *inlined)
    missing: list[str] = [name for name in names if not (root / name).is_file()]
    if missing:
        raise FactoryError(f"{root} is missing {', '.join(missing)}")
    page: str = (root / "dashboard.html").read_text()
    marks: dict[str, str] = {name: f"/* {name} */\n" for name in inlined}
    if any(mark not in page for mark in marks.values()):
        raise FactoryError(f"{root / 'dashboard.html'} is missing its style or script marker")
    for name, mark in marks.items():
        page = page.replace(mark, (root / name).read_text(), 1)
    return page.encode()


def now():
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def parse_time(stamp):
    return datetime.fromisoformat(stamp.replace("Z", "+00:00"))


def run(cmd, cwd=None, check=True, env=None, input=None, timeout=None):
    res = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, env=env, input=input, timeout=timeout)
    if check and res.returncode != 0:
        raise Refused(f"`{' '.join(map(str, cmd))}` failed: {(res.stderr or res.stdout).strip()}")
    return res


def find_repo(start=None):
    """The main checkout, also when called from one of its worktrees."""
    cwd = Path(start or os.getcwd())
    res = subprocess.run(["git", "rev-parse", "--git-dir", "--git-common-dir", "--show-toplevel"],
                         cwd=cwd, capture_output=True, text=True)
    if res.returncode != 0:
        raise Refused(f"{cwd} is not inside a git repository")
    git_dir, common_dir, toplevel = res.stdout.strip().splitlines()
    if (cwd / git_dir).resolve() == (cwd / common_dir).resolve():
        return Path(toplevel).resolve()
    return (cwd / common_dir).resolve().parent


def first_line(path):
    path = Path(path)
    return path.read_text().split("\n", 1)[0].strip() if path.exists() else None


def header(path):
    """`KEY: value` lines at the top of an agent's file, up to the first blank line."""
    fields = {}
    for line in Path(path).read_text().splitlines():
        if not line.strip():
            break
        key, _, value = line.partition(":")
        fields[key.strip().upper()] = value.strip()
    return fields


def body(path):
    """Everything after the header lines of an agent's file."""
    parts = Path(path).read_text().split("\n\n", 1)
    return parts[1].strip() if len(parts) > 1 else ""


def section(path, heading):
    m = re.search(rf"^## {re.escape(heading)}\n(.*?)(?=^## |\Z)", Path(path).read_text(), re.M | re.S)
    return m.group(1).strip() if m else None


def quote(text):
    return "\n".join("> " + line for line in (text.strip() or "(empty)").splitlines())


def tail(text, lines):
    return "\n".join(text.rstrip().splitlines()[-lines:])


def write_atomic(path, text):
    path = Path(path)
    tmp = path.with_name(f"{path.name}.{os.getpid()}.tmp")  # two jobs may write the index at once
    tmp.write_text(text)
    tmp.replace(path)
